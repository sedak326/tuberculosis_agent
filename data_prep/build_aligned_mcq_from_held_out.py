#!/usr/bin/env python3
"""
build_aligned_mcq_from_held_out.py — Build the question-style-aligned eval set FROM the
real held-out SFT pairs we already generated (data_prep/eyeball_prompts_raw.jsonl),
instead of having GPT-4o invent fresh questions. Each held-out pair already has a real
question grounded in a held-out chunk, and a real answer generated by the actual SFT
pipeline (Llama-3.3-70B) — but that answer was never independently checked.

For each pair: pull the real source passage (by source_chunk_id, from corpus_v3_eval.jsonl)
and ask GPT-4o to VERIFY the existing answer against the passage + TB domain knowledge
before trusting it as ground truth:
  - if it holds up: use it as the correct choice, write 3 distractors
  - if it doesn't: write a corrected answer as the new correct choice, and demote the
    original (flawed) answer to one of the distractors — it's a realistic distractor,
    since it's literally what the SFT pipeline produced

Scoped to the 3 categories with a well-defined correct/incorrect structure:
premise_correction, methodology_critique, result_interpretation.

Usage:
    python build_aligned_mcq_from_held_out.py \
        --pairs  eyeball_prompts_raw.jsonl \
        --corpus /uss/skavlak/version_3/corpus_v3_eval.jsonl \
        --out    /uss/skavlak/version_3/aligned_mcq_eval.jsonl
"""

import argparse
import json
import os
import re
import time
from pathlib import Path

from openai import OpenAI

TARGET_CATEGORIES = {"premise_correction", "methodology_critique", "result_interpretation"}

SYSTEM_PROMPT = """\
You are an expert in tuberculosis (TB) research with deep knowledge of microbiology, \
molecular biology, genomics, drug resistance, host-pathogen interactions, and TB \
therapeutics. You are building a rigorous evaluation item from a real question and a \
real candidate answer that was generated by a different, weaker LLM — your job is to \
check that candidate answer like a careful peer reviewer, not assume it is correct."""

VERIFY_PROMPT = """\
Source passage the question was grounded in:
{passage}

Question (from category "{category}"):
{question}

Candidate answer (generated by a different LLM, NOT verified):
{candidate_answer}

Step 1 — Verify: Is the candidate answer actually correct and well-reasoned, given the \
passage and your own TB domain knowledge? Check for factual errors, unsupported claims, \
or places it misses the actual point of the question.

Step 2 — Build the eval item:
- If the candidate answer holds up: use it (you may lightly tidy wording, but keep its \
substance) as the CORRECT choice. Then write 3 distractor answers, each wrong in one \
specific way: one factually incorrect, one that misses the key issue, one generic/evasive.
- If the candidate answer does NOT hold up: write a new, correct, well-reasoned answer as \
the CORRECT choice. Use the original (flawed) candidate answer, essentially as-is, as ONE \
of the 3 distractors (labeled with its real flaw). Write 2 more distractors to fill out \
the remaining wrong-in-a-specific-way slots (prefer "factually incorrect" and "misses the \
key issue" / "generic" for these two, whichever the original distractor didn't already \
cover).

All four answers should be paragraph-length, plausible-sounding, and similar in length/tone \
— a reader shouldn't be able to spot the correct one just because it's longer or more \
confident.

Respond with valid JSON only, using this exact format:
{{
  "verdict": "original_verified" or "original_replaced",
  "verification_notes": "1-2 sentences on what you checked and why the candidate answer passed or failed",
  "choices": {{
    "A": "...",
    "B": "...",
    "C": "...",
    "D": "..."
  }},
  "correct": "A",
  "explanation": "The correct answer is A because ... Choice B is wrong because ... Choice C is wrong because ... Choice D is wrong because ..."
}}"""


def load_corpus_by_id(corpus_path: str) -> dict:
    by_id = {}
    with open(corpus_path, encoding="utf-8") as f:
        for line in f:
            obj = json.loads(line)
            cid = obj.get("id")
            if cid:
                by_id[cid] = obj
    return by_id


def strip_header(text: str) -> str:
    return text[text.index("\n\n") + 2:] if "\n\n" in text else text


def parse_response(text: str) -> dict | None:
    text = re.sub(r"^```(?:json)?\s*", "", text.strip())
    text = re.sub(r"\s*```$", "", text.strip())
    try:
        return json.loads(text)
    except json.JSONDecodeError:
        return None


def validate_item(item: dict) -> bool:
    required = {"verdict", "choices", "correct", "explanation"}
    if not required.issubset(item.keys()):
        return False
    if item["verdict"] not in {"original_verified", "original_replaced"}:
        return False
    if set(item["choices"].keys()) != {"A", "B", "C", "D"}:
        return False
    if item["correct"] not in {"A", "B", "C", "D"}:
        return False
    for v in item["choices"].values():
        if len(v.strip()) < 40:
            return False
    return True


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--pairs", default="eyeball_prompts_raw.jsonl")
    ap.add_argument("--corpus", default="/uss/skavlak/version_3/corpus_v3_eval.jsonl")
    ap.add_argument("--out", default="/uss/skavlak/version_3/aligned_mcq_eval.jsonl")
    ap.add_argument("--model", default="gpt-4o")
    ap.add_argument("--limit", type=int, default=None, help="cap total items, for a pilot run")
    ap.add_argument("--resume", action="store_true")
    args = ap.parse_args()

    client = OpenAI(api_key=os.environ["OPENAI_API_KEY"])

    print("Loading held-out pairs...")
    pairs = [json.loads(l) for l in open(args.pairs, encoding="utf-8")]
    pairs = [p for p in pairs if p.get("category") in TARGET_CATEGORIES]
    print(f"  {len(pairs)} pairs in target categories: {TARGET_CATEGORIES}")

    print("Loading held-out corpus (for passage lookup)...")
    by_id = load_corpus_by_id(args.corpus)
    print(f"  {len(by_id)} chunks indexed")

    out_path = Path(args.out)
    out_path.parent.mkdir(parents=True, exist_ok=True)

    done_chunk_ids = set()
    if args.resume and out_path.exists():
        with open(out_path, encoding="utf-8") as f:
            for line in f:
                done_chunk_ids.add(json.loads(line).get("source_chunk_id", ""))
        print(f"Resuming: {len(done_chunk_ids)} already done")

    counts = {c: 0 for c in TARGET_CATEGORIES}
    verdict_counts = {"original_verified": 0, "original_replaced": 0}
    failed = 0
    n_written = 0

    # IMPORTANT: when resuming, counts must start from how many of each
    # category already exist in the output file, not from zero - otherwise
    # new records get the same ids as existing ones (id = f"amcq_{category}_
    # {counts[category]}"), silently colliding on resume. Bit us once already.
    if args.resume and out_path.exists():
        for line in open(out_path, encoding="utf-8"):
            cat = json.loads(line).get("cognitive_level")
            if cat in counts:
                counts[cat] += 1
        print(f"Resuming category counts: {counts}")

    with open(out_path, "a", encoding="utf-8") as f:
        for p in pairs:
            if args.limit and n_written >= args.limit:
                break
            chunk_id = p.get("_source_chunk_id") or p.get("source_chunk_id")
            if chunk_id in done_chunk_ids:
                continue
            chunk = by_id.get(chunk_id)
            if chunk is None:
                print(f"  [skip] chunk {chunk_id} not found in corpus")
                failed += 1
                continue

            category = p["category"]
            msgs = p["messages"]
            question = next(m["content"] for m in msgs if m["role"] == "user")
            # strip the instruction preamble, keep just the input portion for display
            answer = next(m["content"] for m in msgs if m["role"] == "assistant")
            passage = strip_header(chunk.get("text", ""))[:3000]

            try:
                resp = client.chat.completions.create(
                    model=args.model,
                    messages=[
                        {"role": "system", "content": SYSTEM_PROMPT},
                        {"role": "user", "content": VERIFY_PROMPT.format(
                            passage=passage, category=category, question=question,
                            candidate_answer=answer)},
                    ],
                    temperature=0.5,
                    max_tokens=1800,
                    response_format={"type": "json_object"},
                )
                item = parse_response(resp.choices[0].message.content)
                if item is None or not validate_item(item):
                    print(f"  [skip] invalid item for chunk {chunk_id} ({category})")
                    failed += 1
                    continue

                record = {
                    "id": f"amcq_{category}_{counts[category]:03d}",
                    "source_chunk_id": chunk_id,
                    "document_name": chunk.get("document_name", ""),
                    "cognitive_level": category,
                    "question": question,
                    "topic": "aligned_eval",
                    **item,
                }
                f.write(json.dumps(record, ensure_ascii=False) + "\n")
                f.flush()
                counts[category] += 1
                verdict_counts[item["verdict"]] += 1
                n_written += 1
                print(f"  [{n_written}] {category} -> {item['verdict']}")
                time.sleep(0.5)

            except Exception as e:
                print(f"  [error] {e}")
                failed += 1
                time.sleep(2)

    print(f"\nDone. {n_written} items saved to {out_path} ({failed} failed/skipped)")
    print(f"Per-category: {dict(counts)}")
    print(f"Verdicts: {verdict_counts}")


if __name__ == "__main__":
    main()
